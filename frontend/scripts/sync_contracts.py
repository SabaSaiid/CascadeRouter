"""Generate frontend contracts from this repository's OpenAPI, without a server."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.main import create_app
from backend.schemas import ERROR_MESSAGES


OPERATIONS = {
    "Health": ("/api/health", "get", "200"),
    "Scan": ("/api/scan", "post", "200"),
    "JobAccepted": ("/api/benchmark", "post", "202"),
    "Job": ("/api/runs/{run_id}", "get", "200"),
    "Optimization": ("/api/optimize", "post", "200"),
    "PatchAccepted": ("/api/patches", "post", "201"),
    "Patch": ("/api/patches/{patch_id}", "get", "200"),
    "Validation": ("/api/patches/{patch_id}/validate", "post", "201"),
}
KEYS = {"$ref", "type", "properties", "required", "additionalProperties", "items", "prefixItems", "anyOf", "oneOf",
        "allOf", "enum", "const", "pattern", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum",
        "minLength", "maxLength", "minItems", "maxItems", "format"}


def _type(schema):
    if "$ref" in schema:
        return "Backend_" + re.sub(r"\W", "_", schema["$ref"].split("/")[-1])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join("(" + _type(item) + ")" for item in schema.get("anyOf", schema.get("oneOf")))
    kind = schema.get("type")
    if kind == "array":
        if "prefixItems" in schema:
            return "readonly [" + ", ".join(_type(item) for item in schema["prefixItems"]) + "]"
        return "ReadonlyArray<" + _type(schema.get("items", {})) + ">"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = ["readonly " + json.dumps(key) + ("" if key in required else "?") + ": " + _type(value)
                  for key, value in schema.get("properties", {}).items()]
        additional = schema.get("additionalProperties", False)
        if additional is not False:
            fields.append("readonly [key: string]: " + (_type(additional) if isinstance(additional, dict) else "unknown"))
        return "{ " + "; ".join(fields) + " }"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def _strip(schema):
    result = {}
    for key, value in schema.items():
        if key not in KEYS:
            continue
        if key == "properties": value = {name: _strip(item) for name, item in value.items()}
        elif key in ("items", "additionalProperties") and isinstance(value, dict): value = _strip(value)
        elif key in ("anyOf", "oneOf", "allOf", "prefixItems"): value = [_strip(item) for item in value]
        result[key] = value
    return result


def render_contract():
    api = create_app().openapi()
    models = {alias: api["paths"][path][method]["responses"][status]["content"]["application/json"]["schema"]["$ref"].split("/")[-1]
              for alias, (path, method, status) in OPERATIONS.items()}
    for alias, path in (("ScanRequest", "/api/scan"), ("BenchmarkRequest", "/api/benchmark"),
                        ("OptimizationRequest", "/api/optimize"), ("PatchRequest", "/api/patches")):
        models[alias] = api["paths"][path]["post"]["requestBody"]["content"]["application/json"]["schema"]["$ref"].split("/")[-1]
    models["ApiErrorResponse"] = "ErrorResponse"
    all_schemas, selected = api["components"]["schemas"], {}
    def include(name):
        if name in selected: return
        selected[name] = _strip(all_schemas[name])
        def walk(value):
            if isinstance(value, dict):
                if "$ref" in value: include(value["$ref"].split("/")[-1])
                for item in value.values(): walk(item)
            elif isinstance(value, list):
                for item in value: walk(item)
        walk(selected[name])
    for name in models.values(): include(name)
    lines = ["// Generated by scripts/sync_contracts.py from first-party OpenAPI. Do not edit."]
    for name, schema in sorted(selected.items()):
        lines.append("export type Backend_" + re.sub(r"\W", "_", name) + " = " + _type(schema) + ";")
    for alias, name in sorted(models.items()):
        lines.append("export type " + alias + " = Backend_" + re.sub(r"\W", "_", name) + ";")
    lines.append("export const modelNames = " + json.dumps(models, sort_keys=True) + " as const;")
    lines.append("export const schemas: Record<string, unknown> = " + json.dumps(selected, sort_keys=True, separators=(",", ":")) + ";")
    lines.append("export const errorMessages: Record<string, string> = " + json.dumps(dict(ERROR_MESSAGES), sort_keys=True) + ";")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "frontend" / "src" / "services" / "contracts.ts"
    expected = render_contract()
    if args.check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != expected:
            sys.exit("Frontend contracts differ from current OpenAPI; run frontend/scripts/sync_contracts.py.")
        print("Frontend contracts match current first-party OpenAPI.")
    else:
        destination.write_text(expected, encoding="utf-8", newline="\n")
